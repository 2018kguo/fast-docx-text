// Writes crates/fast-docx-text/src/dingbats.rs from dingbat-to-unicode (BSD-2-Clause,
// Michael Williamson), the table mammoth reads `w:sym` through:
// (TYPEFACE_dingbat, Unicode scalar).
//   npm install && node scripts/generate-dingbats.mjs
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";

const fromJs = createRequire(path.resolve(import.meta.dirname, "../js/package.json"));
const fromMammoth = createRequire(fromJs.resolve("mammoth/package.json"));
const { version } = fromMammoth("dingbat-to-unicode/package.json");
const dingbats = fromMammoth("dingbat-to-unicode/dist/dingbats.js").default;
// { TYPEFACE: { codePoint: unicodeCodePoint } }, looked up as
// dingbats[typeface.toUpperCase()][parseInt(char, 16)].
const rows = new Map();
for (const [typeface, codes] of Object.entries(dingbats)) {
  for (const [code, unicode] of Object.entries(codes)) {
    rows.set(`${typeface}_${code}`, unicode);
  }
}
const entries = [...rows].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
const out = `// @generated by scripts/generate-dingbats.mjs from dingbat-to-unicode ${version}.
// Copyright (c) 2013, Michael Williamson. BSD-2-Clause; see NOTICE.
//! \`(TYPEFACE_dingbat, code point)\`, sorted by key, for binary search.

pub const DINGBATS: &[(&str, u32)] = &[
${entries.map(([key, value]) => `    (${JSON.stringify(key)}, ${value}),`).join("\n")}
];
`;
writeFileSync(
  path.resolve(import.meta.dirname, "../crates/fast-docx-text/src/dingbats.rs"),
  out
);
console.log(`${entries.length} dingbats from dingbat-to-unicode ${version}`);
