// Writes crates/fast-docx-text/src/dingbats.rs from dingbat-to-unicode (BSD-2-Clause,
// Michael Williamson), the table mammoth reads `w:sym` through:
// per typeface, the Unicode scalar of each dingbat code.
//   npm install && node scripts/generate-dingbats.mjs
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";

const fromJs = createRequire(path.resolve(import.meta.dirname, "../js/package.json"));
const fromMammoth = createRequire(fromJs.resolve("mammoth/package.json"));
const { version } = fromMammoth("dingbat-to-unicode/package.json");
const dingbats = fromMammoth("dingbat-to-unicode/dist/dingbats.js").default;
// { TYPEFACE: { codePoint: unicodeCodePoint } }, looked up as
// dingbats[typeface.toUpperCase()][parseInt(char, 16)].
// One 256-entry table per typeface, 0 where a code has no mapping (none maps to 0).
const typefaces = Object.keys(dingbats).sort();
const tables = typefaces.map((typeface) => {
  const table = new Array(256).fill(0);
  for (const [code, unicode] of Object.entries(dingbats[typeface])) {
    if (!(Number(code) >= 0 && Number(code) < 256) || unicode === 0) {
      throw new Error(`${typeface} ${code}: outside the table's shape`);
    }
    table[Number(code)] = unicode;
  }
  return table;
});
const count = tables.flat().filter(Boolean).length;
const out = `// @generated by scripts/generate-dingbats.mjs from dingbat-to-unicode ${version}.
// Copyright (c) 2013, Michael Williamson. BSD-2-Clause; see NOTICE.
//! Per typeface (upper case), the Unicode scalar for each dingbat code 0-255; 0 for none.

pub const DINGBATS: [(&str, [u32; 256]); ${typefaces.length}] = [
${typefaces
  .map(
    (typeface, i) =>
      `    (\n        ${JSON.stringify(typeface)},\n        [${tables[i].join(", ")}],\n    ),`
  )
  .join("\n")}
];
`;
writeFileSync(
  path.resolve(import.meta.dirname, "../crates/fast-docx-text/src/dingbats.rs"),
  out
);
console.log(`${count} dingbats from dingbat-to-unicode ${version}`);
