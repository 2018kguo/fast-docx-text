// Writes js/wasm/fast_docx_text.wasm.js from the freshly built .wasm beside it: the
// module as base64 in a JavaScript string, so it loads the same way everywhere (no
// file to find, fetch or bundle beside the code).
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const wasm = path.resolve(import.meta.dirname, "../js/wasm/fast_docx_text.wasm");
// Base64 with `r` written as `-` and `R` as `_`; js/src/index.ts swaps them back.
const base64 = readFileSync(wasm).toString("base64").replaceAll("r", "-").replaceAll("R", "_");
writeFileSync(
  `${wasm}.js`,
  `// @generated by scripts/build-wasm.sh from crates/fast-docx-text.\n` +
    `export const WASM_BASE64 =\n  "${base64}";\n`
);
writeFileSync(
  `${wasm}.d.ts`,
  `// @generated by scripts/build-wasm.sh.\nexport declare const WASM_BASE64: string;\n`
);
